    def get_skill_by_subject(subject, level):
        # 简单映射：level 1-10 对应 列表索引 0-9
        # 如果越界，取最后一个
        
        # 转换 Subject 枚举名为属性名
        attr_name = ""
        if "数学" in subject: attr_name = "MATH"
        elif "物理" in subject: attr_name = "PHYSICS"
        elif "化学" in subject: attr_name = "CHEM"
        elif "生物" in subject: attr_name = "BIO"
        elif "信奥" in subject: attr_name = "INFO"
        elif "语文" in subject: attr_name = "CHN"
        elif "英语" in subject: attr_name = "ENG"
        else: return ("基础知识", 1, "平平无奇")

        skills = getattr(SkillTree, attr_name, [])
        if not skills: return ("基础知识", 1, "平平无奇")
        
        # Scale level roughly
        idx = min(len(skills)-1, max(0, int(level // 1000) - 1))
        # Use simpler mapping for now: Random or sequential based on mastery?
        # Let's return a random skill up to the mastery level
        unlocked = skills[:idx+1]
        if not unlocked: return skills[0]
        return random.choice(unlocked)

